#!/usr/bin/env python3
"""Collect model-comparison metrics and print report-table numbers."""

from __future__ import annotations

import argparse
import csv
import json
import sys
from dataclasses import dataclass
from pathlib import Path

from nba_forecasting.model_comparison import FULL_SPECS, REPORT_TABLE_SPECS, latest_run_dir


@dataclass(frozen=True)
class RunMetrics:
    label: str
    run_dir: Path
    ckpt_sel_val_ade: float | None
    ckpt_sel_epoch: int | None
    val_ade: float | None
    val_tta_xy_ade: float | None
    holdout_ade: float | None
    holdout_tta_xy_ade: float | None


def _read_scalar(path: Path, keys: tuple[str, ...]) -> float | None:
    if not path.exists():
        return None
    payload = json.loads(path.read_text())
    for key in keys:
        value = payload.get(key)
        if isinstance(value, int | float):
            return float(value)
    return None


def _read_ade(path: Path) -> float | None:
    return _read_scalar(path, ("mse", "ade"))


def _history_best(run_dir: Path) -> tuple[float | None, int | None]:
    history = run_dir / "history.csv"
    if not history.exists():
        return None, None
    rows = list(csv.DictReader(history.open()))
    if not rows:
        return None, None
    metric_key = "val_mse" if "val_mse" in rows[0] else "val_ade"
    best = min(rows, key=lambda row: float(row[metric_key]))
    return float(best[metric_key]), int(best["epoch"])


def _collect_run(label: str, root: Path, folder_name: str) -> RunMetrics | None:
    run_dir = latest_run_dir(root, folder_name)
    if run_dir is None:
        return None
    ckpt_val, ckpt_epoch = _history_best(run_dir)
    return RunMetrics(
        label=label,
        run_dir=run_dir,
        ckpt_sel_val_ade=ckpt_val,
        ckpt_sel_epoch=ckpt_epoch,
        val_ade=_read_ade(run_dir / "eval_val" / "metrics.json"),
        val_tta_xy_ade=_read_ade(run_dir / "eval_val_tta_xy" / "metrics.json"),
        holdout_ade=_read_ade(run_dir / "eval_holdout" / "metrics.json"),
        holdout_tta_xy_ade=_read_ade(run_dir / "eval_holdout_tta_xy" / "metrics.json"),
    )


def _fmt(value: float | None) -> str:
    return f"{value:.4f}" if value is not None else "--"


def _markdown_table(rows: list[RunMetrics]) -> str:
    header = "| Model | Val | Val + TTA | Holdout | Holdout + TTA |"
    sep = "| --- | ---: | ---: | ---: | ---: |"
    lines = [header, sep]
    for row in rows:
        lines.append(
            f"| {row.label} | {_fmt(row.val_ade)} | {_fmt(row.val_tta_xy_ade)} | {_fmt(row.holdout_ade)} | {_fmt(row.holdout_tta_xy_ade)} |"
        )
    return "\n".join(lines) + "\n"


def _latex_table(rows: list[RunMetrics]) -> str:
    lines = [
        "% Auto-generated by scripts/collect_results.py",
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Model & Val & Val + TTA & Holdout & Holdout + TTA \\\\",
        "\\midrule",
    ]
    for row in rows:
        lines.append(
            f"{row.label} & {_fmt(row.val_ade)} & {_fmt(row.val_tta_xy_ade)} & "
            f"{_fmt(row.holdout_ade)} & {_fmt(row.holdout_tta_xy_ade)} \\\\"
        )
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    return "\n".join(lines) + "\n"


def _audit_lines(rows: list[RunMetrics]) -> list[str]:
    lines: list[str] = []
    for row in rows:
        lines.append(f"[audit] {row.label} run_dir={row.run_dir}")
        if row.ckpt_sel_val_ade is not None:
            lines.append(f"  checkpoint-selection val_ade={row.ckpt_sel_val_ade:.4f} @ epoch {row.ckpt_sel_epoch}")
    return lines


def _print_report_table(specs: list[tuple[str, Path, str]]) -> int:
    print(f"{'Model':<34} {'ADE (ft)':>10} {'ADE_sq':>10} {'FDE (ft)':>10}")
    print("-" * 68)
    missing = 0
    for label, root, folder_name in specs:
        run_dir = latest_run_dir(root, folder_name)
        if run_dir is None:
            print(f"{label:<34} {'--':>10} {'--':>10} {'--':>10}")
            missing += 1
            continue
        metrics_path = run_dir / "eval_holdout_tta_xy" / "metrics.json"
        ade_l2 = _read_scalar(metrics_path, ("ade_l2",))
        ade_sq = _read_scalar(metrics_path, ("mse", "ade"))
        fde = _read_scalar(metrics_path, ("fde_l2",))
        if ade_sq is None or ade_l2 is None or fde is None:
            print(f"{label:<34} {'--':>10} {'--':>10} {'--':>10}")
            missing += 1
            continue
        print(f"{label:<34} {ade_l2:10.3f} {ade_sq:10.3f} {fde:10.3f}")
    if missing:
        print(
            "\n"
            f"{missing} row(s) missing — run: "
            "python -m nba_forecasting model-comparison --smoke && "
            "python -m nba_forecasting model-comparison",
            file=sys.stderr,
        )
        return 1
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--report-table-only",
        action="store_true",
        help="Print holdout+xy-TTA report-table numbers only (no files written).",
    )
    parser.add_argument(
        "--require-complete",
        action="store_true",
        help="Exit nonzero if any model-comparison row is missing holdout+xy-TTA metrics.",
    )
    parser.add_argument("--output-dir", type=Path, default=Path("report/generated"))
    args = parser.parse_args(argv)

    if args.report_table_only:
        return _print_report_table(REPORT_TABLE_SPECS)

    rows: list[RunMetrics] = []
    for label, root, folder_name in FULL_SPECS:
        metrics = _collect_run(label, root, folder_name)
        if metrics is not None:
            rows.append(metrics)

    if args.require_complete:
        missing = [row.label for row in rows if row.holdout_tta_xy_ade is None]
        if len(rows) < len(FULL_SPECS) or missing:
            print(
                f"ERROR: incomplete model comparison ({len(rows)}/{len(FULL_SPECS)} rows; missing metrics: {missing})",
                file=sys.stderr,
            )
            return 1

    args.output_dir.mkdir(parents=True, exist_ok=True)
    table_md = _markdown_table(rows)
    table_tex = _latex_table(rows)
    (args.output_dir / "model_comparison.md").write_text(table_md)
    (args.output_dir / "model_comparison.tex").write_text(table_tex)

    print(table_md)
    print("--- report table (holdout + xy TTA) ---")
    report_status = _print_report_table(REPORT_TABLE_SPECS)
    print("--- audit ---")
    for line in _audit_lines(rows):
        print(line)
    print(f"Wrote {args.output_dir / 'model_comparison.tex'}")
    return report_status


if __name__ == "__main__":
    raise SystemExit(main())
